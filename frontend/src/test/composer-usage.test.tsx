import { afterEach, expect, it, vi } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { ComposerFooter } from '../components/mauzcode/ComposerFooter';
const props = { agentId:'fixture', busy:false, running:false, revision:0 };
const result = (input: number | null, output: number | null, ratio: number | null) => ({ budget:{estimatedTokens:8000,contextWindow:200000}, details:{breakdown:null,session:{},usage:{inputTokens:input,outputTokens:output,cacheHitRatio:ratio,cachedInputTokens:3000000,cacheWriteTokens:100000,requests:5}} });
afterEach(() => vi.unstubAllGlobals());
it('shows compact input and output, keeps exact numbers in the accessible name and opens the details panel from the metrics row', async () => {
 vi.stubGlobal('fetch', vi.fn(async()=>Response.json(result(184220,9412,.87))));
 render(<ComposerFooter {...props}/>);
 expect(await screen.findByText('184k')).toBeInTheDocument(); expect(screen.getByText('9.4k')).toBeInTheDocument(); expect(screen.getByText('↑')).toBeInTheDocument(); expect(screen.getByText('↓')).toBeInTheDocument(); expect(screen.getByText('кэш 87%')).toBeInTheDocument();
 const metrics=screen.getByRole('button',{name:/4% of context used.*Input: 184,220 tok. Output: 9,412 tok. Попадание в кэш 87%/});
 expect(metrics).toHaveTextContent('4%');
 expect(screen.getAllByRole('button')).toEqual([metrics]);
 expect(metrics).toHaveAttribute('aria-expanded','false');
 await userEvent.click(metrics);
 const dialog=await screen.findByRole('dialog',{name:'Context usage'});
 expect(dialog).toHaveTextContent('Token usage'); expect(metrics).toHaveAttribute('aria-controls',dialog.id);
 expect(metrics).toHaveAttribute('aria-expanded','true');
 await userEvent.keyboard('{Escape}');
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull());
});
it('keeps missing usage distinct from measured zero', async () => {
 vi.stubGlobal('fetch',vi.fn(async()=>Response.json(result(null,null,null))));
 const ui=render(<ComposerFooter {...props}/>);
 await screen.findByText('4%');
 const tokens=()=>[...document.querySelectorAll('.composer-token-count .rolling-number-sr')].map(node=>node.textContent);
 expect(tokens()).toEqual(['—','—']); expect(screen.getByText('кэш —')).toBeInTheDocument();
 vi.stubGlobal('fetch',vi.fn(async()=>Response.json(result(0,0,0))));
 ui.rerender(<ComposerFooter {...props} revision={1}/>);
 await waitFor(()=>expect(tokens()).toEqual(['0','0'])); expect(screen.getByText('кэш 0%')).toBeInTheDocument();
});
